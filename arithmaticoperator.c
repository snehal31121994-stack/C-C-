#include<stdio.h>
int main()
{
    int a = 17;
    int b = 5;
    int add = a+b;
    int sub = a-b;
    int mul = a*b;
    int div = a/b;
    int rem = a%b;

    
    printf("Addition = %d\n",add);
    printf("Substraction = %d\n",sub);
    printf("Multiplication = %d\n",mul);
    printf("Integer Division = %d\n",div);
    printf(" Remainder= %d\n",rem);

    

    return 0;
}